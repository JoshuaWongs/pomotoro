GLYPHS = {k: v.split() for k, v in _G.items()}
MISSING = GLYPHS["?"]


def text_width(s, px):
    """Rendered width in screen pixels for a glyph size of `px`."""
    return max(0, (len(s) * (W + GAP) - GAP)) * px


def runs(s, px, bold=False):
    """Yield (x, y, w, h) rectangles for `s`, relative to its top-left corner.

    Consecutive lit pixels on a row become one rectangle -- roughly a third of
    the items a naive per-pixel draw would create. `bold` smears each run one
    pixel to the right, the usual way to thicken a bitmap face without drawing
    a second alphabet.
    """
    for i, ch in enumerate(s):
        rows = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or MISSING
        ox = i * (W + GAP) * px
        for ry, row in enumerate(rows):
            x = 0
            while x < W:
                if row[x] == "1":
                    run = 1
                    while x + run < W and row[x + run] == "1":
                        run += 1
                    yield (ox + x * px, ry * px, run * px + (px if bold else 0), px)
                    x += run
                else:
                    x += 1
